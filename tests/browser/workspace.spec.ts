test('real files folder import archive export and restore through the interface', async ({ page }) => {
  test.skip(process.env.E2E_WRITE !== 'donarium_test' || !process.env.E2E_PASSWORD, 'Requires the isolated browser test server with FIXTURES storage.');
  test.setTimeout(90000);
  const login=await page.request.post('/api/v1/auth/login',{data:{password:process.env.E2E_PASSWORD}});
  expect(login.ok()).toBe(true);
  await page.goto('/catalog/new');
  await page.getByLabel('Название',{exact:true}).fill(`Файловая проверка ${Date.now()}`);
  await page.getByRole('button',{name:'Сохранить карточку'}).click();
  await expect(page.getByRole('button',{name:'Связать файл или папку'})).toBeVisible();
  const productId=page.url().split('/').at(-1)!;
  await page.getByRole('button',{name:'Связать файл или папку'}).click();
  await page.getByRole('combobox',{name:'Хранилище',exact:true}).selectOption('FIXTURES');
  await page.getByRole('checkbox',{name:'Выбрать Example Model',exact:true}).check();
  await page.getByRole('button',{name:'Связать выбранное (1)',exact:true}).click();
  await expect(page.locator('.asset-row')).toHaveCount(2);
  const model=page.locator('.asset-row').filter({has:page.getByRole('heading',{name:'part.stl',exact:true})});
  const [single]=await Promise.all([page.waitForEvent('download'),model.getByRole('link',{name:'Скачать',exact:true}).click()]);
  expect(single.suggestedFilename()).toBe('part.stl');
  expect(await single.failure()).toBeNull();
  await expect(page.getByRole('link',{name:'Скачать всё ZIP'})).toBeVisible();
  const [bundle]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Скачать всё ZIP'}).click()]);
  expect(bundle.suggestedFilename()).toMatch(/\.zip$/);
  expect(await bundle.failure()).toBeNull();
  await model.getByRole('button',{name:'Отвязать part.stl',exact:true}).click();
  await model.getByRole('button',{name:'Подтвердить отвязку'}).click();
  await expect(page.getByRole('heading',{name:'part.stl',exact:true})).toHaveCount(0);
  const original=await page.request.get('/api/v1/storage/browse?root=FIXTURES&path=Example%20Model');
  expect((await original.json()).entries.some((entry:{name:string})=>entry.name==='part.stl')).toBe(true);
  await page.goto('/import');
  await page.getByRole('combobox',{name:'Хранилище',exact:true}).selectOption('FIXTURES');
  await page.getByRole('button',{name:'Сканировать эту папку'}).click();
  await expect(page.locator('.import-item')).toHaveCount(1);
  await expect(page.locator('.import-item')).toContainText('обложка найдена');
  await page.locator('.import-item input').check();
  await page.getByRole('button',{name:'Импортировать выбранное (1)',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Результат импорта'})).toBeVisible();
  await expect(page.locator('.operation-report')).toContainText('Создано');
  await page.getByRole('button',{name:'Новое сканирование'}).click();
  await page.getByRole('combobox',{name:'Хранилище',exact:true}).selectOption('FIXTURES');
  await page.getByRole('button',{name:'Сканировать эту папку'}).click();
  await expect(page.locator('.import-item')).toContainText('обновление связей существующей карточки');
  await page.getByRole('button',{name:'Отменить операцию'}).click();
  await page.goto('/transfer');
  const [json]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'JSON',exact:true}).click()]);
  expect(await json.failure()).toBeNull();
  const [csv]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'CSV',exact:true}).click()]);
  expect(await csv.failure()).toBeNull();
  const beforeRestore = await page.request.get('/api/v1/products?pageSize=1');
  const originalTotal = (await beforeRestore.json()).total as number;
  expect(originalTotal).toBeGreaterThan(0);
  await page.getByRole('button',{name:'Подготовить полный архив'}).click();
  await expect(page.getByRole('link',{name:'Скачать архив'})).toBeVisible({timeout:30000});
  const [archive]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Скачать архив'}).click()]);
  expect(await archive.failure()).toBeNull();
  const archivePath=await archive.path();
  expect(archivePath).toBeTruthy();
  await page.getByRole('button',{name:'Закрыть и удалить временные файлы'}).click();
  await page.locator('input[type=file]').setInputFiles(archivePath!);
  await expect(page.getByRole('heading',{name:'Предварительный результат'})).toBeVisible({timeout:30000});
  await page.getByRole('combobox',{name:'Если ID уже существует',exact:true}).selectOption('copy');
  await page.getByRole('button',{name:'Подтвердить восстановление'}).click();
  await expect(page.getByText('Восстановление завершено.',{exact:true})).toBeVisible({timeout:30000});
  await page.goto('/catalog');
  await expect(page.locator('.product-card')).toHaveCount(originalTotal * 2);
  await page.locator('.product-grid').evaluate(element=>element.getAnimations({subtree:true}).forEach(animation=>animation.finish()));
  await page.screenshot({path:'var/qa/library-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.sidebar').evaluate(element=>element.getAnimations().forEach(animation=>animation.finish()));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'var/qa/library-mobile.png',fullPage:true});
  const removed=await page.request.delete(`/api/v1/products/${productId}`);
  expect(removed.status()).toBe(204);
});
