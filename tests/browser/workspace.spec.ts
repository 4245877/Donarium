test('downloaded JSON restores favorites and profile through the import dialog', async ({ page }) => {
  await page.goto('/catalog');
  const card = page.locator('.product-card').first();
  await expect(card).toBeVisible();
  const title = (await card.getByRole('heading', { level: 3 }).innerText()).trim();
  await card.getByRole('button', { name: `В избранное: ${title}`, exact: true }).click();
  await page.goto('/settings');
  await page.getByLabel('Ваше имя', { exact: true }).fill('Хранитель знаний');
  await page.getByRole('button', { name: 'Сохранить настройки', exact: true }).click();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Скачать копию', exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toMatch(/^echidna-workspace-\d{4}-\d{2}-\d{2}\.json$/);
  const path = await download.path();
  expect(path).toBeTruthy();
  const backup = JSON.parse(await readFile(path!, 'utf8')) as { version: number; favorites: string[]; settings: { name: string } };
  expect(backup.version).toBe(1);
  expect(backup.favorites).toHaveLength(1);
  expect(backup.settings.name).toBe('Хранитель знаний');
  await page.goto('/favorites');
  await page.getByRole('button', { name: 'Убрать из избранного', exact: true }).click();
  await page.goto('/settings');
  await page.getByLabel('Ваше имя', { exact: true }).fill('Другое имя');
  await page.getByRole('button', { name: 'Сохранить настройки', exact: true }).click();
  await page.getByLabel('Файл резервной копии', { exact: true }).setInputFiles(path!);
  const dialog = page.getByRole('dialog', { name: 'Восстановить пространство?', exact: true });
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Восстановить', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByLabel('Ваше имя', { exact: true })).toHaveValue('Хранитель знаний');
  await page.goto('/favorites');
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
});

test('malformed and unknown import fields show feedback without replacing current data', async ({ page }) => {
  await page.goto('/settings');
  await page.getByLabel('Ваше имя', { exact: true }).fill('Сохранённое имя');
  await page.getByRole('button', { name: 'Сохранить настройки', exact: true }).click();
  await page.getByLabel('Файл резервной копии', { exact: true }).setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{ broken JSON') });
  let dialog = page.getByRole('dialog', { name: 'Восстановить пространство?', exact: true });
  await dialog.getByRole('button', { name: 'Восстановить', exact: true }).click();
  await expect(page.locator('.w-toast')).toContainText('Файл не содержит корректный JSON.');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Отмена', exact: true }).click();
  const invalid = { version: 1, favorites: [], collections: [], activity: [], settings: { name: 'Потерянное имя', theme: 'light', animations: true, compact: false }, unknown: 'rejected' };
  await page.getByLabel('Файл резервной копии', { exact: true }).setInputFiles({ name: 'unknown-fields.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(invalid)) });
  dialog = page.getByRole('dialog', { name: 'Восстановить пространство?', exact: true });
  await dialog.getByRole('button', { name: 'Восстановить', exact: true }).click();
  await expect(page.locator('.w-toast')).toContainText('Файл содержит неизвестные поля.');
  await page.keyboard.press('Escape');
  await expect(page.getByLabel('Ваше имя', { exact: true })).toHaveValue('Сохранённое имя');
  await page.reload();
  await expect(page.getByLabel('Ваше имя', { exact: true })).toHaveValue('Сохранённое имя');
});

test('mobile navigation opens, closes after routing and stays within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  const menu = page.locator('.mobile-menu');
  await expect(menu).toBeVisible();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await expect(page.locator('.sidebar')).toHaveAttribute('inert', '');
  const closedTabTargets: boolean[] = [];
  for (let index = 0; index < 6; index++) {
    await page.keyboard.press('Tab');
    closedTabTargets.push(await page.evaluate(() => Boolean(document.activeElement?.closest('.sidebar'))));
  }
  expect(closedTabTargets).toEqual(Array<boolean>(6).fill(false));
  await menu.click();
  await expect(menu).toHaveAttribute('aria-expanded', 'true');
  const sidebarControls = page.locator('.sidebar').locator('a[href], button:not([disabled])');
  await sidebarControls.last().focus();
  await page.keyboard.press('Tab');
  await expect(sidebarControls.first()).toBeFocused();
  await page.getByRole('navigation', { name: 'Основная навигация', exact: true }).getByRole('link', { name: 'Избранное', exact: true }).click();
  await expect(page.getByRole('heading', { name: /^Избранное/ })).toBeVisible();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await menu.click();
  await page.getByRole('navigation', { name: 'Управление пространством', exact: true }).getByRole('link', { name: 'Настройки', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Настройки пространства', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto('/collections?new=1');
  await expect(page.getByRole('dialog', { name: 'Новая коллекция', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.keyboard.press('Escape');
  await menu.click();
  await page.getByRole('button', { name: 'Закрыть меню', exact: true }).click();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
});

test('tea dialog displays its timer and Escape restores focus', async ({ page }) => {
  await page.goto('/');
  const invitation = page.getByRole('button', { name: 'Минута спокойствия', exact: true });
  await invitation.click();
  const dialog = page.getByRole('dialog', { name: 'Побудь здесь немного.', exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog.locator('.breathing-circle span')).toHaveText(/^[01]:\d{2}$/);
  await expect(dialog.locator('.breathing-circle span')).not.toHaveText('1:00', { timeout: 5000 });
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(invitation).toBeFocused();
});
