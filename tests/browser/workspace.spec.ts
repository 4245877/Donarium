  await editButton.click();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(editButton).toBeFocused();
  await editButton.click();
  const editor = page.getByRole('dialog', { name: 'Изменить коллекцию', exact: true });
  await editor.getByLabel('Название', { exact: true }).fill('Сад знаний');
  await editor.getByLabel(/Описание/).fill('Обновлённая история моей коллекции');
