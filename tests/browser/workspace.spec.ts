import { test, expect } from '@playwright/test';

test('owner login uses one password and exposes errors', async ({ page }) => {
  let authenticated = false;
  await page.route('**/api/v1/auth/session', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ configured: true, authenticated, readOnly: false }) }));
  await page.route('**/api/v1/auth/login', async route => {
    const password = route.request().postDataJSON().password;
    authenticated = password === 'test-owner-password';
    await route.fulfill({ status: authenticated ? 200 : 401, contentType: 'application/json', body: JSON.stringify(authenticated ? { authenticated: true } : { error: { message: 'Неверный пароль' } }) });
  });
  await page.goto('/catalog');
  await expect(page.getByLabel('Пароль владельца')).toBeVisible();
  await page.getByLabel('Пароль владельца').fill('wrong');
  await page.getByRole('button', { name: 'Открыть библиотеку' }).click();
  await expect(page.getByRole('alert')).toContainText('Неверный пароль');
  await page.getByLabel('Пароль владельца').fill('test-owner-password');
  await page.getByRole('button', { name: 'Открыть библиотеку' }).click();
  await expect(page.getByRole('heading', { name: /^Каталог моделей/ })).toBeVisible();
});

