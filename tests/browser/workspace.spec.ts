  await expect(picker).toBeVisible();
  const model = picker.locator('.w-product-option').first();
  await expect(model).toBeVisible();
  const title = (await model.locator('strong').innerText()).trim();
  await model.click();
  await expect(model).toHaveAttribute('aria-pressed', 'true');
